"""Write js/tracks.js, the sound check's Spotify previews, from a list of Spotify track links.

    python website/tracks.py

Each track's 30-second preview, title, artists and cover come from its public Spotify embed page
(the data Spotify's own embed player uses). Run this again if a preview stops loading; Spotify
sometimes moves them. Not published with the site.
"""

import json
import re
import urllib.request
from pathlib import Path

TRACKS = [
    "https://open.spotify.com/track/1eiKvtqhLkQOWWcwCmMyHs",
    "https://open.spotify.com/track/3Wz7pxyNhuXiURWSl9WHkv",
    "https://open.spotify.com/track/4DxiWZ5hOK5pLxn7jaiiSZ",
    "https://open.spotify.com/track/5f8FrcgWhUQF8rkkZgjLIz",
]
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
OUT = Path(__file__).resolve().parent / "js" / "tracks.js"


def track(link: str) -> dict:
    tid = re.search(r"track/([A-Za-z0-9]+)", link).group(1)
    req = urllib.request.Request(f"https://open.spotify.com/embed/track/{tid}", headers={"User-Agent": UA})
    html = urllib.request.urlopen(req, timeout=20).read().decode("utf-8")
    data = json.loads(re.search(r'<script id="__NEXT_DATA__" type="application/json">(.*?)</script>', html, re.S).group(1))
    e = data["props"]["pageProps"]["state"]["data"]["entity"]
    preview = (e.get("audioPreview") or {}).get("url")
    if not preview:
        raise SystemExit(f"{link}: Spotify has no preview for this track")
    images = sorted((e.get("visualIdentity") or {}).get("image") or [], key=lambda i: i.get("maxWidth", 0))
    cover = next((i["url"] for i in images if i.get("maxWidth", 0) >= 300), images[-1]["url"] if images else None)
    return {
        "id": tid,
        "title": e.get("title") or e.get("name"),
        "artists": [a["name"] for a in e.get("artists", [])],
        "explicit": bool(e.get("isExplicit")),
        "preview": preview,
        "cover": cover,
        "url": f"https://open.spotify.com/track/{tid}",
    }


if __name__ == "__main__":
    tracks = [track(t) for t in TRACKS]
    OUT.write_text(
        "// The sound check's music: 30-second previews streamed from Spotify when a visitor presses\n"
        "// play, rotating through this list. Generated by website/tracks.py; edit the links there.\n"
        f"export const TRACKS = {json.dumps(tracks, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
        newline="\n",
    )
    for t in tracks:
        print(f"{t['title']} - {', '.join(t['artists'])}")
